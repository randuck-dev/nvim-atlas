local perf = require("atlas.perf")

describe("atlas.perf", function()
  before_each(function()
    perf.reset()
  end)

  it("labels commands by program and subcommand", function()
    assert.are.equal("git status", perf.label({ "git", "-C", "/x", "status", "--porcelain" }))
    assert.are.equal("git rev-list", perf.label({ "git", "--no-optional-locks", "-C", "/x", "-c", "a=b", "rev-list" }))
    assert.are.equal("claude-status json", perf.label({ "/home/u/bin/claude-status", "json" }))
    assert.are.equal("gh pr list", perf.label({ "gh", "pr", "list", "-R", "a/b" }))
    assert.are.equal("tmux attach-session", perf.label({ "env", "-u", "TMUX", "tmux", "attach-session", "-t", "x" }))
    assert.are.equal("ps", perf.label({ "ps" }))
  end)

  it("records processes, with :wait() and on_exit both still working", function()
    local got
    local r = perf.system({ "sh", "-c", "echo hi" }, { text = true }, function(res)
      got = res.stdout
    end):wait()
    assert.are.equal("hi\n", r.stdout)
    vim.wait(1000, function()
      return got ~= nil
    end)
    assert.are.equal("hi\n", got)
    perf.system({ "sh", "-c", "exit 3" }):wait()
    local s = perf.snapshot()
    assert.are.equal(2, s.procs["sh -c"].n)
    assert.are.equal(1, s.procs["sh -c"].fail)
    assert.are.equal(0, s.running)
  end)

  it("counts git calls that failed on the index lock", function()
    perf.system({
      "sh",
      "-c",
      "echo \"fatal: Unable to create '/r/.git/index.lock': File exists.\" >&2; exit 128",
    }, { text = true }):wait()
    local s = perf.snapshot()
    assert.are.equal(1, s.lock_fails)
    assert.are.equal(1, s.procs["sh -c"].lock)
    assert.truthy(table.concat(perf.report(), "\n"):find("1 git call%(s%) failed on a lock"))
  end)

  it("runs every process without git's optional locks", function()
    local r = perf.system({ "sh", "-c", 'printf %s "$GIT_OPTIONAL_LOCKS"' }, { text = true }):wait()
    assert.are.equal("0", r.stdout)
    -- The caller's own env still applies.
    r = perf.system({ "sh", "-c", 'printf %s "$FOO"' }, { text = true, env = { FOO = "bar" } }):wait()
    assert.are.equal("bar", r.stdout)
  end)

  it("raises spawn failures like vim.system, and doesn't count them as running", function()
    assert.has_error(function()
      perf.system({ "/no/such/program" })
    end)
    local s = perf.snapshot()
    assert.are.equal(0, s.running)
    assert.are.equal(1, s.spawn_fails)
  end)

  it("measures Lua work, passing results and errors through", function()
    local a, b, c = perf.measure("adds", function(x, y)
      return x + y, nil, "z"
    end, 1, 2)
    assert.are.equal(3, a)
    assert.is_nil(b)
    assert.are.equal("z", c)
    assert.has_error(function()
      perf.measure("adds", function()
        error("boom")
      end)
    end)
    perf.count("ticks")
    local s = perf.snapshot()
    assert.are.equal(2, s.lua.adds.n)
    assert.are.equal(1, s.lua.ticks.n)
  end)

  it("reports CPU, including exited children", function()
    perf.system({ "sh", "-c", "i=0; while [ $i -lt 20000 ]; do i=$((i+1)); done" }):wait()
    local s = perf.snapshot()
    assert.truthy(s.cpu_self >= 0)
    assert.is_not_nil(s.cpu_children)
    assert.truthy(s.cpu_children > 0)
    local text = table.concat(perf.report(), "\n")
    assert.truthy(text:find("Neovim itself", 1, true))
    assert.truthy(text:find("sh -c", 1, true))
  end)

  it(":AtlasStats opens the report and q closes it", function()
    require("atlas").setup({})
    vim.cmd("AtlasStats")
    local b = vim.api.nvim_get_current_buf()
    assert.are.equal("AtlasStats", vim.bo[b].filetype)
    assert.truthy(vim.api.nvim_buf_get_lines(b, 0, 1, false)[1]:find("atlas stats", 1, true))
    vim.cmd("close")
    assert.is_false(vim.api.nvim_buf_is_valid(b))
  end)
end)
